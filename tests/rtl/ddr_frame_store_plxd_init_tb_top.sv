// Top wrapper: ddr_frame_store with NO doorbell traffic.
// Observes DDRAM write transactions for PLXD @ BANK_MAILBOX_PHYS.
`timescale 1ns/1ps
module ddr_frame_store_plxd_init_tb (
	input  wire        clk,
	input  wire        clk_ddr,
	input  wire        reset,
	input  wire        rd_active,
	input  wire [9:0]  rd_x,
	input  wire [8:0]  rd_y,
	input  wire        vsync_pulse,
	// Force doorbell bus returns to zeros (no PLXK)
	input  wire [63:0] DDRAM_DOUT,
	input  wire        DDRAM_BUSY,
	input  wire        DDRAM_DOUT_READY,
	output wire        DDRAM_CLK,
	output wire  [7:0] DDRAM_BURSTCNT,
	output wire [28:0] DDRAM_ADDR,
	output wire        DDRAM_RD,
	output wire [63:0] DDRAM_DIN,
	output wire  [7:0] DDRAM_BE,
	output wire        DDRAM_WE,
	output wire        has_frame,
	output wire        swap_pending,
	output wire [15:0] frames_done,
	output wire        doorbell_ok
);
	ddr_frame_store #(
		.FRAME_W(64),
		.FRAME_H(32),
		.FRAME_STRIDE(64),
		.CODED_W(64),
		.CODED_H(32),
		.DISPLAY_W(64),
		.DISPLAY_H(32),
		.LINE_COUNT(4),
		.PHYS_BASE(32'h3000_0000),
		.HPS_BANK_STRIDE_BYTES(524288),
		// Product-like doorbell page; mailbox stays absolute default 0x3007F128
		.DOORBELL_PHYS(32'h300F_F000),
		.BANK_MAILBOX_PHYS(32'h3007_F128),
		.PIPELINE_REFILL_SCHEDULER(1'b0),
		.STRICT_YUV_DOORBELL(1'b1)
	) dut (
		.clk(clk),
		.clk_ddr(clk_ddr),
		.reset(reset),
		.rd_x(rd_x),
		.rd_y(rd_y),
		.rd_active(rd_active),
		.rd_r(), .rd_g(), .rd_b(),
		.start_req(1'b0),
		.bank_sel(1'b0),
		.status_osd(16'd0),
		.input_cmd_valid(1'b0),
		.input_cmd(8'd0),
		.sdram_test_state(4'd0),
		.sdram_size_code(4'd0),
		.sdram_error_count(16'd0),
		.DDRAM_CLK(DDRAM_CLK),
		.DDRAM_BUSY(DDRAM_BUSY),
		.DDRAM_BURSTCNT(DDRAM_BURSTCNT),
		.DDRAM_ADDR(DDRAM_ADDR),
		.DDRAM_DOUT(DDRAM_DOUT),
		.DDRAM_DOUT_READY(DDRAM_DOUT_READY),
		.DDRAM_RD(DDRAM_RD),
		.DDRAM_DIN(DDRAM_DIN),
		.DDRAM_BE(DDRAM_BE),
		.DDRAM_WE(DDRAM_WE),
		.vsync_pulse(vsync_pulse),
		.has_frame(has_frame),
		.swap_pending(swap_pending),
		.underrun_count(),
		.frames_done(frames_done),
		.doorbell_ok(doorbell_ok),
		.debug_state()
	);
endmodule
